// Generates ToC.md from the files, the sidecars and the "Planned topics" lists of the READMEs.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { LibNode } from '../shared/types';
import { repoFiles } from './check';
import { resolveRules } from '../shared/project';
import { extractSummary, extractTitle } from '../shared/text';
import { loadLibrary } from './library';

const ROOT_ORDER = ['README.md', 'GUIDELINE.md', 'AGENTS.md', 'CLAUDE.md', '.gitignore'];
const href = (p: string): string => p.split('/').map((s) => encodeURIComponent(s).replace(/%26/g, '&')).join('/');

function firstSentence(text: string, max = 170): string {
  const cut = text.search(/[.!?](\s|$)/);
  const s = cut > 0 ? text.slice(0, cut + 1) : text;
  return s.length > max ? `${s.slice(0, max - 3).trimEnd()}...` : s;
}

function plannedTopics(markdown: string): string[] {
  const m = /^## Planned topics\s*\n([\s\S]*?)(?=^## |(?![\s\S]))/m.exec(markdown);
  return m ? (m[1] ?? '').split('\n').filter((l) => l.startsWith('- ')).map((l) => l.slice(2).trim()) : [];
}

export function buildToc(root: string): string {
  const lib = loadLibrary(root);
  if (!lib.config) throw new Error(lib.issues.map((i) => i.message).join('\n'));
  const rules = resolveRules(lib.config);
  const descriptions = lib.config.toc?.descriptions ?? {};
  const byPath = new Map<string, LibNode>(lib.nodes.map((n) => [n.path, n]));
  const md = new Map(lib.files.map((f) => [f.path, f.markdown]));
  const files = repoFiles(root).filter((f) => !f.endsWith('.md.json'));

  const describe = (path: string): string => {
    const node = byPath.get(path);
    if (node) return `${node.title} - ${firstSentence(node.summary)}`.trim();
    if (descriptions[path]) return descriptions[path] ?? '';
    // A Markdown file outside the entry points (README, GUIDELINE) is described by its own heading.
    if (path.endsWith('.md') && existsSync(join(root, path))) {
      const text = readFileSync(join(root, path), 'utf8');
      const title = extractTitle(text);
      const summary = extractSummary(text);
      if (title) return summary ? `${title} - ${firstSentence(summary)}` : title;
    }
    return 'File.';
  };
  const sortKey = (dirPath: string, name: string, isDir: boolean): [number, number, string] => {
    const rel = dirPath ? `${dirPath}/${name}` : name;
    const node = isDir ? byPath.get(`${rel}/README.md`) : byPath.get(rel);
    const top = dirPath === '' ? (isDir ? 2 : ROOT_ORDER.includes(name) ? 0 : name === rules.tocFile ? 0 : 1) : name === 'README.md' ? 0 : 1;
    const rank = dirPath === '' && !isDir ? (name === rules.tocFile ? 1 : ROOT_ORDER.indexOf(name) + 2) : (node?.order ?? 1e6);
    return [top, rank, name];
  };

  const lines: string[] = [];
  const children = (dir: string): { name: string; isDir: boolean }[] => {
    const prefix = dir ? `${dir}/` : '';
    const seen = new Map<string, boolean>();
    for (const f of files) {
      if (!f.startsWith(prefix)) continue;
      const rest = f.slice(prefix.length);
      const slash = rest.indexOf('/');
      seen.set(slash < 0 ? rest : rest.slice(0, slash), slash >= 0);
    }
    return [...seen].map(([name, isDir]) => ({ name, isDir })).sort((a, b) => {
      const ka = sortKey(dir, a.name, a.isDir);
      const kb = sortKey(dir, b.name, b.isDir);
      return ka[0] - kb[0] || ka[1] - kb[1] || ka[2].localeCompare(kb[2]);
    });
  };

  const walk = (dir: string, depth: number): void => {
    const pad = '  '.repeat(depth);
    for (const c of children(dir)) {
      const path = dir ? `${dir}/${c.name}` : c.name;
      if (c.isDir) {
        const readme = byPath.get(`${path}/README.md`);
        lines.push(`${pad}- **${c.name}/**${readme?.planned ? ' (planned)' : ''}`);
        walk(path, depth + 1);
        if (readme?.planned) for (const t of plannedTopics(md.get(readme.path) ?? '')) lines.push(`${pad}  - ${t} (planned)`);
        continue;
      }
      lines.push(`${pad}- [${c.name}](${href(path)}): ${describe(path)}`);
    }
  };
  // Root files sit under one heading entry, as before.
  const rootFiles = children('').filter((c) => !c.isDir);
  lines.push('- **Repository root**');
  for (const c of rootFiles) lines.push(`  - [${c.name}](${href(c.name)}): ${c.name === rules.tocFile ? 'This file.' : describe(c.name)}`);
  for (const c of children('').filter((x) => x.isDir)) {
    lines.push(`- **${c.name}/**${byPath.get(`${c.name}/README.md`)?.planned ? ' (planned)' : ''}`);
    walk(c.name, 1);
    const readme = byPath.get(`${c.name}/README.md`);
    if (readme?.planned) for (const t of plannedTopics(md.get(readme.path) ?? '')) lines.push(`  - ${t} (planned)`);
  }

  return [
    '# Table of contents',
    '',
    'Full tree of every file in the repository. Generated by Librarian OS (`npm run toc`) from the files, the note titles and the planned topics in the READMEs. Sidecar files (`.md.json`) are not listed: the entry of their Markdown file covers them.',
    '',
    'Entries without a link are planned topics. They become notes or directories when they are written.',
    '',
    ...lines,
    '',
  ].join('\n');
}

export function writeToc(root: string): number {
  const lib = loadLibrary(root);
  const file = lib.config ? resolveRules(lib.config).tocFile : 'ToC.md';
  const text = buildToc(root);
  writeFileSync(join(root, file), text);
  return text.split('\n').length;
}

